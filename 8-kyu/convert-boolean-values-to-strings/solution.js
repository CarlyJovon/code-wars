//Complete the method that takes a boolean value 
//and return a "Yes" string for true, or a "No" string for false.

//create a function named boolToWord that takes one parameter(bool)
//check if bool is true - return "Yes"
//if not true, return "No"

function boolToWord( bool ){
    if (bool === true){ 
        return "Yes";
    }else{
        return "No";
    }
}

